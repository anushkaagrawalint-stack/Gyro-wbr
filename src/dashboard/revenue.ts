import { BOOT, Chart, DATA, LOCATIONS, PERIODS, css, grid, money, pct, pill, usdTip, varPct, view } from './core';

/* =========================================================================
   REVENUE CHANNELS
   Hierarchy is read from the "Toast" tab of WBR Input.xlsx: bold purple rows
   (A1,A3,A9,A15,A21) = channel headers, plain rows beneath = dining-option
   lines. Dining-option names in the Toast Weekly-* sheets are matched to
   these lines after stripping case/spaces/punctuation (e.g. "DoorDash -  Delivery",
   "Doordash Delivery" -> "DoorDash - Delivery").
   DATA[view.period].rev[location] = { actual:{line:val}, ly:{}, bud:{}, lw:{} }
   ========================================================================= */
export const CHANNELS = BOOT.channels;
export const REV_LOCS = BOOT.user?.role === 'location' ? [...LOCATIONS] : ['All Locations', ...LOCATIONS];   // a location login chooses among their own restaurants only


/* ---- per-location Toast sheets (generated by tools/add_location_sheet.py; edit only through that tool) ----
   LOC_DATA[view.period][actual|ly][location] = { total: net sales, lines: { toast line: net sales }, tab: source tab name }
   feeds Overview (DATA[view.period].actual/ly[location]) and Revenue Channels (DATA[view.period].rev[location]) */
export const EXTRA_LINES: Record<string, string> = {};        // the admin mapping puts every dining option on a real line
if (BOOT) Object.keys(EXTRA_LINES).forEach(k => delete EXTRA_LINES[k]);     // with the admin backend every line is already in BOOT.channels
Object.entries(EXTRA_LINES).forEach(([line, ch]) => { const c = CHANNELS.find(x => x.name === ch); if (c && !c.lines.includes(line)) c.lines.push(line); });
export const LOC_DATA = BOOT.locData;
Object.entries(LOC_DATA).forEach(([p, kinds]) => {
  DATA[p] = DATA[p] || {};
  Object.entries(kinds).forEach(([kind, byLoc]) => Object.entries(byLoc).forEach(([loc, v]) => {
    if (loc === 'All Locations') (DATA[p].totals = DATA[p].totals || {})[kind] = v.total;   // overall (all-locations) sheet
    else (DATA[p][kind] = DATA[p][kind] || {})[loc] = v.total;
    DATA[p].rev = DATA[p].rev || {}; (DATA[p].rev[loc] = DATA[p].rev[loc] || {})[kind] = v.lines;
    DATA[p].cats = DATA[p].cats || {}; (DATA[p].cats[loc] = DATA[p].cats[loc] || {})[kind] = v.cats || {};   // sales categories under each line
  }));
});

export let revLoc = REV_LOCS[0], revFilter = 'All', openLines = new Set();   // openLines: subcategories (dining-option lines) whose sales categories are shown   // revFilter: 'All' = channels only; a channel name = that channel with its subcategories
document.getElementById('revLoc').innerHTML = REV_LOCS.map(l => `<option>${l}</option>`).join('');
if (REV_LOCS.length === 1) document.getElementById('revLoc').style.display = 'none';   // one restaurant: nothing to choose
document.getElementById('revLoc').addEventListener('change', e => { revLoc = e.target.value; renderRevenue(); });
document.getElementById('revFilter').addEventListener('change', e => { revFilter = e.target.value; renderRevenue(); });

export const revBar = new Chart(document.getElementById('revChart'), {
  type:'bar',
  data:{ labels:CHANNELS.map(c=>c.name), datasets:[
    { label:'Actual', data:[], backgroundColor:'#9f7cef', borderRadius:4 },
    { label:'LY',     data:[], backgroundColor:'rgba(209,213,219,0.7)', borderRadius:4 },
    { label:'Budget', data:[], backgroundColor:'#93c5fd', borderRadius:4 } ]},
  options:{ maintainAspectRatio:false,
    plugins:{ legend:{ position:'bottom', labels:{ boxWidth:36, boxHeight:12, color:css('--muted') } }, tooltip:{ callbacks:{ label:usdTip } } },
    scales:{ y:{ beginAtZero:true, grid:grid(), ticks:{ color:css('--muted'), callback:v=>v.toLocaleString('en-US') } },
             x:{ grid:grid(), ticks:{ color:css('--muted') } } } }
});
export const donutLabels = { id:'donutLabels', afterDatasetsDraw(ch){
  const ds = ch.data.datasets[0], tot = ds.data.reduce((s,x)=>s+(x||0),0), ctx = ch.ctx;
  if(!tot){ ctx.save(); ctx.fillStyle=css('--muted'); ctx.font='500 12.1px Inter, sans-serif'; ctx.textAlign='center';
    ctx.fillText('No data yet', ch.chartArea.left+ch.chartArea.width/2, ch.chartArea.top+ch.chartArea.height/2); ctx.restore(); return; }
  ch.getDatasetMeta(0).data.forEach((arc,i) => { const v = ds.data[i]||0; if(v/tot < .04) return;
    const p = arc.tooltipPosition(); ctx.save(); ctx.fillStyle='#fff'; ctx.font='700 11.3px Inter, sans-serif'; ctx.textAlign='center'; ctx.textBaseline='middle';
    ctx.fillText((v/tot*100).toFixed(1)+'%', p.x, p.y); ctx.restore(); });
}};
export const mixChart = new Chart(document.getElementById('mixChart'), {
  type:'doughnut',
  data:{ labels:CHANNELS.map(c=>c.name), datasets:[{ data:[], backgroundColor:CHANNELS.map(c=>c.color), borderWidth:2, borderColor:'#fff' }]},
  options:{ maintainAspectRatio:false, cutout:'55%', plugins:{ legend:{ position:'bottom', labels:{ color:css('--muted'), boxWidth:36, boxHeight:12 } }, tooltip:{ callbacks:{ label:usdTip } } } },
  plugins:[donutLabels]
});

export function renderRevenue(){
  const P = PERIODS[view.period], r = DATA[view.period]?.rev?.[revLoc] || {};
  const get = (k, line) => r[k] ? (r[k][line] ?? (line in EXTRA_LINES ? 0 : undefined)) : undefined;   // an extra (not-on-the-list) line missing from a series counts as $0
  const chSum = (k, c) => r[k] ? c.lines.reduce((s,l)=>s+(get(k,l)||0),0) : null;
  const tot = k => r[k] ? CHANNELS.reduce((s,c)=>s+chSum(k,c),0) : null;
  const lineVals = (c, line) => ({ a:get('actual',line), l:get('ly',line), b:get('bud',line), w:get('lw',line) });
  const chVals = c => ({ a:chSum('actual',c), l:chSum('ly',c), b:chSum('bud',c), w:chSum('lw',c) });
  const dlr = (a,b) => (a==null||b==null) ? '-' : money(a-b);
  const cells = v => `<td>${money(v.a)}</td><td>${pill(varPct(v.a,v.w))}</td><td>${money(v.l)}</td><td>${dlr(v.a,v.l)}</td><td>${pill(varPct(v.a,v.l))}</td><td>${money(v.b)}</td><td>${dlr(v.a,v.b)}</td><td>${pill(varPct(v.a,v.b))}</td>`;

  if (BOOT.user?.role === 'location') {                                              // a restaurant login: Sales and Growth cards above the charts
    const ta = tot('actual'), tl = tot('ly'), tw = tot('lw');
    let k = document.getElementById('revKpis');
    if (!k) { k = document.createElement('section'); k.id = 'revKpis'; k.className = 'kpis'; k.style.gridTemplateColumns = 'repeat(auto-fit,minmax(240px,1fr))';
      document.querySelector('#view-revenue > .filters').after(k); }
    const card = (t, v, d) => `<div class="card kpi"><div class="k">${t}</div><div class="v">${v}</div><div class="d">${d}</div></div>`;
    k.innerHTML = card(P.title, money(ta), `Var%: ${pct(varPct(ta, tw))} vs LW`) +
      card('Growth vs Last Year', money(tl), `Var%: ${pct(varPct(ta, tl))}<br>Var $:${ta == null || tl == null ? '-' : money(ta - tl)}`);
  }
  document.getElementById('revBarTitle').textContent = `Revenue by Channel - ${P.label} vs LY & Budget`;
  document.getElementById('revMixTitle').textContent = `Actual Revenue Mix - ${P.label}`;

  let html = '';
  const hasAny = !!(r.actual || r.ly || r.bud);                                      // a view with no data at all keeps the empty skeleton (dashes)
  const there = l => hasAny ? ['actual','ly','bud'].some(k => get(k,l)) : !(l in EXTRA_LINES);   // a line that is zero / missing in every series is "not there" for this location (empty views keep the standard skeleton)
  const chRow = c => `<tr class="ch" data-ch="${c.name}"><td>${c.name}</td>${cells(chVals(c))}</tr>`;
  const visCh = CHANNELS.filter(c => !hasAny || c.lines.some(there));                 // channels that have something in this view
  // filter = "All Channels" + just the channel names (a channel with nothing in this view is not offered)
  const sel = document.getElementById('revFilter'), sig = visCh.map(c => c.name).join('|');
  if (sel.dataset.sig !== sig) { sel.innerHTML = '<option value="All">All Channels</option>' + visCh.map(c => `<option value="${c.name}">${c.name}</option>`).join(''); sel.dataset.sig = sig; }
  if (revFilter !== 'All' && !visCh.some(c => c.name === revFilter)) revFilter = 'All';
  sel.value = revFilter;
  if (revFilter === 'All') {
    visCh.forEach(c => { html += chRow(c); });                                        // channels only
    html += `<tr class="tot"><td>Total</td>${cells({ a:tot('actual'), l:tot('ly'), b:tot('bud'), w:tot('lw') })}</tr>`;
  } else {                                                                            // one channel opened from the filter: its row + its subcategories
    const c = CHANNELS.find(x => x.name === revFilter);
    c.lines.filter(there).forEach(l => { html += `<tr class="sub" data-line="${l.replace(/&/g,'&amp;').replace(/"/g,'&quot;').replace(/</g,'&lt;')}"><td>${l}</td>${cells(lineVals(c,l))}</tr>`; });
    html += `<tr class="tot"><td>Total</td>${cells(chVals(c))}</tr>`;                 // the channel's own figures now sit on a Total line under its subcategories
  }
  document.getElementById('revBody').innerHTML = html;

  // the charts show exactly what the table shows: the channels in this view, or the lines of the one channel picked in the filter
  const LINE_COL = ['#9f7cef', '#f9a8d4', '#86efac', '#fcd34d', '#93c5fd', '#fdba74', '#a5b4fc', '#6ee7b7'];
  const one = revFilter === 'All' ? null : CHANNELS.find(x => x.name === revFilter);
  const items = one ? one.lines.filter(there).map((l, i) => ({ n:l, col:LINE_COL[i % LINE_COL.length], a:get('actual',l) ?? null, l:get('ly',l) ?? null, b:get('bud',l) ?? null }))
    : visCh.map(c => ({ n:c.name, col:c.color, a:chSum('actual',c), l:chSum('ly',c), b:chSum('bud',c) }));
  document.getElementById('revBarTitle').textContent = one ? `${one.name} by Line - ${P.label} vs LY & Budget` : `Revenue by Channel - ${P.label} vs LY & Budget`;
  document.getElementById('revMixTitle').textContent = one ? `Actual ${one.name} Mix - ${P.label}` : `Actual Revenue Mix - ${P.label}`;
  revBar.data.labels = items.map(x => x.n);
  revBar.data.datasets[0].data = items.map(x => x.a);
  revBar.data.datasets[1].data = items.map(x => x.l);
  revBar.data.datasets[2].data = items.map(x => x.b);
  mixChart.data.labels = items.map(x => x.n);
  mixChart.data.datasets[0].data = items.map(x => x.a || 0);
  mixChart.data.datasets[0].backgroundColor = items.map(x => x.col);
  revBar.update(); mixChart.update();
}


